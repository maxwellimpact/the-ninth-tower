export function buildIcons(scene) {
  for (const [k, rows] of Object.entries(ICONS)) {
    const [c, ctx] = makeCanvas(16, 16);
    grid(ctx, rows, MAP, 1, Math.floor((16 - rows.length) / 2));
    outline(c, 'ink');
    scene.textures.addCanvas(`icon_${k}`, c);
  }
}
